def arrow(p0, p1):
    ax.add_patch(FancyArrowPatch(p0, p1, arrowstyle='-|>,head_length=4.4,head_width=2.0', mutation_scale=1.0,
                 lw=LW_ARR, color=INK, shrinkA=0, shrinkB=0.7, zorder=2, joinstyle='miter', capstyle='butt'))
def down(a, b, fa=0.0, fb=0.0):
    A, B = N[a], N[b]; arrow((A['x'] + fa, A['b']), (B['x'] + fb, B['t']))

