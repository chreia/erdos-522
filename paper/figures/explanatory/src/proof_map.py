def lane(a, b, right):
    """From the side of box a along an outer lane to the same side of box b."""
    A, B = N[a], N[b]; rr = 0.07
    e0, e1 = (A['r'], B['r']) if right else (A['l'], B['l'])
    xl = e0 + LANE if right else e0 - LANE
    sx = 1 if right else -1
    P = [(e0, A['y']), (xl - sx * rr, A['y']), (xl, A['y']), (xl, A['y'] - rr), (xl, B['y'] + rr), (xl, B['y']), (xl - sx * rr, B['y'])]
    codes = [MPath.MOVETO, MPath.LINETO, MPath.CURVE3, MPath.CURVE3, MPath.LINETO, MPath.CURVE3, MPath.CURVE3]
    ax.add_patch(PathPatch(MPath(P, codes), fc='none', ec=INK, lw=LW_ARR, zorder=2, capstyle='butt'))
    arrow(P[-1], (e1, B['y']))
