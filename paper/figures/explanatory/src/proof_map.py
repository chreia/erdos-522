def groups(s):
    """The top-level brace groups of s, skipping escaped characters."""
    out, depth, i = [], 0, 0
    while i < len(s):
        c = s[i]
        if c == '\\': i += 1
        elif c == '{':
            if depth == 0: start = i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: out.append(s[start:i])
        i += 1
    return out
def aux_numbers(path, labels):
    """Number of each label in the aux file. Stops if a label is missing, repeated or of the wrong kind."""
    if not path.is_file(): sys.exit(f'proof_map.py: no aux file {path}. Build the paper or pass its aux file.')
    found = {}
    for line in path.read_text(errors='replace').splitlines():
        if not line.startswith('\\newlabel{'): continue
        g = groups(line[len('\\newlabel'):])
        if len(g) == 2 and g[0] in labels: found.setdefault(g[0], set()).add(tuple(groups(g[1])))
    nums = {}
    for lab, kind in sorted(labels.items()):
        if lab not in found: sys.exit(f'proof_map.py: label {lab} is missing from {path}')
        if len(found[lab]) > 1: sys.exit(f'proof_map.py: label {lab} is defined more than once in {path}')
        f = next(iter(found[lab])); num = f[0]
        if not num or not all(c.isalnum() or c == '.' for c in num):
            sys.exit(f'proof_map.py: label {lab} has the number {num!r} in {path}')
        anchor = f[3].split('.')[0] if len(f) > 3 else None      # hyperref anchor, e.g. theorem.1.2
        want = ('section', 'subsection', 'subsubsection', 'appendix') if kind == 'Section' else ('theorem',)
        if anchor is not None and anchor not in want:
            sys.exit(f'proof_map.py: label {lab} is a {anchor}, not a {kind}, in {path}')
        nums[lab] = num
    return nums
